#!/usr/bin/env python3
"""Tune the VS Code "Wal" theme (dlasagno.wal-theme) to the current palette.

The extension uses the raw pywal palette: a near-black #010101 background and
dark saturated accents that are hard to read on it. This writes overrides for
the Wal themes only into the user's settings.json, between marker comments, so
other themes and hand-written settings stay untouched. VS Code reloads
settings.json on its own, so the editor follows wallpaper changes live.
"""
import json
import os
import re
import sys

SETTINGS = os.environ.get("VSCODE_SETTINGS", os.path.expanduser("~/.config/Code/User/settings.json"))
PALETTE = os.path.expanduser("~/.cache/wal/colors.json")
THEME = "[Wal][Wal Bordered]"


def rgb(h):
    h = h.lstrip("#")
    return [int(h[i:i + 2], 16) for i in (0, 2, 4)]


def mix(a, b, t):
    """Blend color a toward b by t (0..1)."""
    return "#" + "".join(f"{round(x + (y - x) * t):02x}" for x, y in zip(rgb(a), rgb(b)))


def readable(c):
    return mix(c, "#ffffff", 0.35)


def block(name, body, indent):
    pad = " " * indent
    lines = json.dumps(body, indent=2).splitlines()
    inner = "\n".join(pad + line for line in lines)
    return (f"{pad}// wal-{name}-begin (generated by vscode-wal-colors.py)\n"
            f"{pad}\"{THEME}\": {inner.lstrip()},\n"
            f"{pad}// wal-{name}-end\n")


def upsert(text, name, body, parent_key):
    region = re.compile(rf"[ \t]*// wal-{name}-begin.*?// wal-{name}-end\n", re.S)
    if region.search(text):
        indent = len(region.search(text).group(0)) - len(region.search(text).group(0).lstrip(" \t"))
        return region.sub(lambda _: block(name, body, indent), text, count=1)
    opener = re.search(rf"^([ \t]*)\"{re.escape(parent_key)}\"\s*:\s*\{{[ \t]*\n", text, re.M)
    if opener:
        indent = len(opener.group(1)) + 2
        return text[:opener.end()] + block(name, body, indent) + text[opener.end():]
    # Parent object missing: add it as the last top-level key.
    end = text.rstrip().rfind("}")
    head = text[:end].rstrip()
    if not head.endswith(("{", ",")):
        head += ","
    return f"{head}\n  \"{parent_key}\": {{\n{block(name, body, 4)}  }},\n}}\n"


def main():
    if not (os.path.isfile(SETTINGS) and os.path.isfile(PALETTE)):
        return 0
    pal = json.load(open(PALETTE))
    c = pal["colors"]
    bg, fg, accent = pal["special"]["background"], pal["special"]["foreground"], c["color4"]

    base = mix(bg, "#ffffff", 0.07)
    editor = mix(base, accent, 0.14)
    side = mix(base, accent, 0.09)
    edge = mix(base, accent, 0.06)
    colors = {
        "editor.background": editor,
        "editorGutter.background": editor,
        "editor.foreground": fg,
        "editor.lineHighlightBackground": mix(base, accent, 0.22),
        "editor.selectionBackground": accent + "55",
        "editorLineNumber.foreground": mix(fg, editor, 0.55),
        "editorLineNumber.activeForeground": fg,
        "sideBar.background": side,
        "sideBarSectionHeader.background": side,
        "activityBar.background": edge,
        "titleBar.activeBackground": edge,
        "titleBar.inactiveBackground": edge,
        "statusBar.background": edge,
        "tab.activeBackground": editor,
        "tab.inactiveBackground": side,
        "editorGroupHeader.tabsBackground": side,
        "panel.background": editor,
        "terminal.background": editor,
        "input.background": side,
        "dropdown.background": side,
        "list.activeSelectionBackground": accent + "44",
        "list.hoverBackground": accent + "22",
        "focusBorder": accent + "aa",
    }
    tokens = {
        "comments": mix(c["color8"], "#ffffff", 0.30),
        "strings": readable(c["color2"]),
        "keywords": readable(c["color3"]),
        "numbers": readable(c["color5"]),
        "types": readable(c["color6"]),
        "functions": readable(c["color4"]),
        "variables": fg,
    }

    text = open(SETTINGS).read()
    new = upsert(text, "colors", colors, "workbench.colorCustomizations")
    new = upsert(new, "tokens", tokens, "editor.tokenColorCustomizations")
    if new != text:
        tmp = SETTINGS + ".wal-tmp"
        open(tmp, "w").write(new)
        os.replace(tmp, SETTINGS)
    return 0


if __name__ == "__main__":
    sys.exit(main())
