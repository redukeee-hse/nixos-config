#!/usr/bin/env bash
WALJSON="$HOME/.cache/wal/colors.json"

# Fresh system: build the palette from the current wallpaper once.
if [[ ! -r "$WALJSON" ]]; then
   wallpaper="$HOME/.config/current/Wallpapers/Picture.png"
   [[ -r "$wallpaper" ]] || exit 0
   wal -i "$wallpaper" -n -s -q --saturate 0.7 -b 010101 || exit 0
fi

# grab colors from pywal
BG=$(jq -r '.special.background' "$WALJSON")
FG=$(jq -r '.special.foreground' "$WALJSON")
ACCENT=$(jq -r '.colors.color4' "$WALJSON") # tweak which color slot you like
COLOR12=$(jq -r '.colors.color12' "$WALJSON")

# this converts hex to rgba manually
hex_to_rgba() {
   local hex=${1#\#}
   local r=$((16#${hex:0:2}))
   local g=$((16#${hex:2:2}))
   local b=$((16#${hex:4:2}))
   local a=${2:-1}
   echo "rgba(${r}, ${g}, ${b}, ${a})"
}

# SwayNC does not inherit the GTK/Waybar palette.
mkdir -p "$HOME/.config/current"
swaync_tmp=$(mktemp "$HOME/.config/current/.swaync-colors.XXXXXX")
{
   printf '@define-color nc-bg %s;\n' "$(hex_to_rgba "$BG" 0.19)"
   printf '@define-color nc-panel %s;\n' "$(hex_to_rgba "$BG" 0.55)"
   printf '@define-color nc-fg %s;\n' "$FG"
   printf '@define-color nc-accent %s;\n' "$ACCENT"
   printf '@define-color nc-border %s;\n' "$(hex_to_rgba "$ACCENT" 0.5)"
} > "$swaync_tmp"
mv -f "$swaync_tmp" "$HOME/.config/current/swaync-colors.css"
if pgrep -x swaync >/dev/null; then
   timeout 2 swaync-client --reload-css >/dev/null 2>&1 || true
fi

# Rofi launcher palette, see ~/.config/rofi/config.rasi.
rofi_tmp=$(mktemp "$HOME/.config/current/.rofi-colors.XXXXXX")
{
   printf '/* Generated by wal-color-export.sh from the pywal palette. */\n* {\n'
   printf '    bg:           %s;\n' "$(hex_to_rgba "$BG" 0.45)"
   printf '    border-color: %s;\n' "$(hex_to_rgba "$ACCENT" 0.5)"
   printf '    bg-selected:  %s;\n' "$(hex_to_rgba "$FG" 0.12)"
   printf '    fg:           %s;\n' "$(hex_to_rgba "$FG" 0.9)"
   printf '    fg-muted:     %s;\n' "$(hex_to_rgba "$FG" 0.65)"
   printf '    fg-selected:  %s;\n' "$FG"
   printf '    accent:       %s;\n' "$ACCENT"
   printf '    urgent:       %s;\n' "$(jq -r '.colors.color1' "$WALJSON")"
   printf '}\n'
} > "$rofi_tmp"
mv -f "$rofi_tmp" "$HOME/.config/current/rofi-colors.rasi"

# Zathura palette, included from ~/.config/zathura/zathurarc.
zathura_tmp=$(mktemp "$HOME/.config/current/.zathura-colors.XXXXXX")
{
   printf '# Generated by wal-color-export.sh from the pywal palette.\n'
   printf 'set default-bg "%s"\n' "$BG"
   printf 'set default-fg "%s"\n' "$FG"
   printf 'set statusbar-bg "%s"\n' "$BG"
   printf 'set statusbar-fg "%s"\n' "$FG"
   printf 'set inputbar-bg "%s"\n' "$BG"
   printf 'set inputbar-fg "%s"\n' "$FG"
   printf 'set notification-bg "%s"\n' "$BG"
   printf 'set notification-fg "%s"\n' "$FG"
   printf 'set highlight-color "%s"\n' "$(hex_to_rgba "$ACCENT" 0.4)"
   printf 'set highlight-active-color "%s"\n' "$(hex_to_rgba "$COLOR12" 0.5)"
   printf 'set completion-highlight-bg "%s"\n' "$ACCENT"
   printf 'set recolor-lightcolor "%s"\n' "$BG"
   printf 'set recolor-darkcolor "%s"\n' "$FG"
} > "$zathura_tmp"
mv -f "$zathura_tmp" "$HOME/.config/current/zathura-colors"

# Recolor terminals that are already open. wal runs with -s so it never
# broadcasts on its own; VS Code terminals keep their own theme.
for pts in /dev/pts/[0-9]*; do
   [[ -O "$pts" && -w "$pts" ]] || continue
   in_vscode=0
   for pid in $(ps -t "${pts#/dev/}" -o pid= 2>/dev/null); do
      if tr '\0' '\n' < "/proc/$pid/environ" 2>/dev/null | grep -qx 'TERM_PROGRAM=vscode'; then
         in_vscode=1
         break
      fi
   done
   ((in_vscode)) || timeout 1 cp "$HOME/.cache/wal/sequences" "$pts" 2>/dev/null &
done

# VS Code "Wal" theme: readable background and syntax colors from the palette.
"$HOME/.local/share/custom/bin/vscode-wal-colors.py" || true

pkill -SIGUSR2 -x waybar 2>/dev/null || true
# The drop-down tray compiles its SCSS (with the wal palette) on reload.
timeout 2 eww reload >/dev/null 2>&1 || true
"$HOME/.local/share/custom/bin/sync-sddm-theme.sh" || true

# Persist the border palette across Hyprland reloads and apply it immediately.
hypr_colors="$HOME/.config/current/hypr-colors.conf"
hypr_tmp=$(mktemp "${hypr_colors}.XXXXXX")
printf 'general:col.active_border = rgba(%see) rgba(%s88) 45deg\n' "${ACCENT#\#}" "${COLOR12#\#}" > "$hypr_tmp"
mv -f "$hypr_tmp" "$hypr_colors"
hyprctl keyword general:col.active_border "rgba(${ACCENT#\#}ee) rgba(${COLOR12#\#}88) 45deg" >/dev/null 2>&1 || true
